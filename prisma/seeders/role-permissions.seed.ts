/**
 * Admin: ALL permissions
 * Billing User: billing, barcode, invoice history, settings
 */
const ROLE_PERMISSIONS: { roleId: string; permissionId: string }[] = [
  // ── Admin: everything ────────────────────────────────────────
  ...Object.values(PERM).map((permissionId) => ({
    roleId: ADMIN_ROLE_ID,
    permissionId,
  })),

  // ── Billing User: limited set ─────────────────────────────────
  { roleId: BILLING_USER_ROLE_ID, permissionId: PERM.BILLING_VIEW },
  { roleId: BILLING_USER_ROLE_ID, permissionId: PERM.INVOICE_VIEW },
  { roleId: BILLING_USER_ROLE_ID, permissionId: PERM.INVOICE_CREATE },
  { roleId: BILLING_USER_ROLE_ID, permissionId: PERM.BARCODE_VIEW },
  { roleId: BILLING_USER_ROLE_ID, permissionId: PERM.BARCODE_GENERATE },
];

export async function seedRolePermissions(
  prisma: PrismaClient,
): Promise<void> {
  for (const rp of ROLE_PERMISSIONS) {
    await prisma.rolePermission.upsert({
      where: {
        roleId_permissionId: {
          roleId: rp.roleId,
          permissionId: rp.permissionId,
        },
      },
      update: {},
      create: {
        roleId: rp.roleId,
        permissionId: rp.permissionId,
      },
    });
  }
  console.log(
    `  Seeded ${ROLE_PERMISSIONS.length} role-permission mappings`,
  );
}
